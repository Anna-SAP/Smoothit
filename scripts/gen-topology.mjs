// Generates src/vision/meshTriangles.ts from MediaPipe's canonical face tesselation.
// The tesselation ships as an edge list in which every three consecutive edges close a triangle.
import { FaceLandmarker } from '@mediapipe/tasks-vision';
import { writeFileSync } from 'node:fs';

const edges = FaceLandmarker.FACE_LANDMARKS_TESSELATION;
const tris = [];
for (let i = 0; i + 2 < edges.length; i += 3) {
  const [a, b, c] = [edges[i], edges[i + 1], edges[i + 2]];
  if (a.end !== b.start || b.end !== c.start || c.end !== a.start) {
    throw new Error(`edge triple ${i} does not close a triangle`);
  }
  tris.push(a.start, b.start, c.start);
}
const body = `// AUTO-GENERATED by scripts/gen-topology.mjs — do not edit.
// ${tris.length / 3} triangles over the 468 MediaPipe face-mesh vertices.
export const MESH_TRIANGLES = new Uint16Array([${tris.join(',')}]);
`;
writeFileSync(new URL('../src/vision/meshTriangles.ts', import.meta.url), body);
console.log(`wrote ${tris.length / 3} triangles`);
